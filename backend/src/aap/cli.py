def _rules_dir_files(override: Path) -> list[Path]:
    """The rules files a directory provides. Hidden directories are skipped and symlinks followed: Kubernetes mounts
    a ConfigMap as `config -> ..data/config`, with `..data -> ..<timestamp>` holding the real files."""
    from pathlib import Path

    found: list[Path] = []
    for here, dirs, names in os.walk(override, followlinks=True):
        dirs[:] = [d for d in dirs if not d.startswith(".")]
        found += [
            Path(here) / n
            for n in names
            if not n.startswith(".") and Path(n).suffix in {".yaml", ".yml", ".json", ".jsonl"}
        ]
    return sorted(found)


def _rules_files_read(bundle: ConfigBundle) -> set[str]:
    """Every rules file the platform reads: the governed documents plus the ones read directly."""
    from aap.config import repo_root

    paths = {d.path for d in bundle.documents.values()}
    paths |= {"config/eol-products.yaml", "config/sigstore/trusted_root.jsonl"}
    frameworks = repo_root() / "catalogue" / "frameworks"
    paths |= {f"catalogue/frameworks/{p.name}" for p in frameworks.glob("asvs-*-requirements.yaml")}
    return paths


def cmd_config_check(args: argparse.Namespace) -> None:
    """Show where each rules file comes from; fail on a file in AAP_RULES_DIR the platform never reads (a typo)."""
    from aap.config import ConfigBundle, rules_dir, rules_source

    bundle = ConfigBundle.load()
    for doc in sorted(bundle.documents.values(), key=lambda d: d.path):
        print(f"{doc.source:<10}  {doc.path:<48}  {doc.version:<12}  {doc.sha256[:12]}")
    for rel in sorted({"config/eol-products.yaml", "config/sigstore/trusted_root.jsonl"}):
        print(f"{rules_source(rel):<10}  {rel}")
    override = rules_dir()
    if override is None:
        print("AAP_RULES_DIR is not set: every rules file is the default shipped in the image")
        return
    known = _rules_files_read(bundle)
    unknown = [rel for p in _rules_dir_files(override) if (rel := str(p.relative_to(override))) not in known]
    for rel in unknown:
        print(f"unused    {rel}  (not a rules file the platform reads: check the path)", file=sys.stderr)
    if unknown:
        raise SystemExit(1)


def cmd_config_chart_values(args: argparse.Namespace) -> None:
    """Print AAP_RULES_DIR's files as Helm values (rules.files), for `helm upgrade -f`."""
    from aap.config import rules_dir

    override = rules_dir()
    if override is None:
        raise SystemExit("set AAP_RULES_DIR to the directory holding your rules (config/..., catalogue/...)")
    files = _rules_dir_files(override)
    if not files:
        raise SystemExit(f"{override} holds no rules files")
    out = [
        "# Generated by `aap config chart-values` from your rules directory. Use: helm upgrade ... -f this-file",
        "rules:",
        "  files:",
    ]
    for p in files:
        out.append(f"    {p.relative_to(override)}: |")
        out.extend(f"      {line}" if line else "" for line in p.read_text().rstrip("\n").split("\n"))
    print("\n".join(out))


